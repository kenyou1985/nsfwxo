export function 按分类筛选主题(分类?: ThemeCategory): ThemeEntry[] {
  if (!分类) return THEME_LIBRARY;
  return THEME_LIBRARY.filter((t) => t.category === 分类);
}

export function 按强度筛选主题(强度?: Intensity): ThemeEntry[] {
  if (!强度) return THEME_LIBRARY;
  return THEME_LIBRARY.filter((t) => t.intensity === 强度);
}

export function 随机抽取主题(数量: number, 分类?: ThemeCategory, 强度?: Intensity): ThemeEntry[] {
  const pool = THEME_LIBRARY.filter((t) =>
    (!分类 || t.category === 分类) && (!强度 || t.intensity === 强度)
  );
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(数量, shuffled.length));
}

export function 根据时长生成分镜(主题: ThemeEntry, 时长: 15 | 30 | 60): ThemeBeat[] {
  if (时长 === 15) return 主题.beat15s;
  if (时长 === 60) return 主题.beat60s;
  return 主题.beat30s;
}

export function 主题转视频提示词(主题: ThemeEntry, 时长: 15 | 30 | 60): string {
  const beats = 根据时长生成分镜(主题, 时长);
  const header = `subject_definitions: <Picture 1> ${主题.multiRef ? 'and <Picture 2> ' : ''}as the protagonist(s) of this video.\n\nscenario: ${主题.scenario}\n\nshot_breakdown:`;
  const body = beats.map((b) => `[${b.scene}] ${b.prompt}`).join('\n\n');
  return `${header}\n\n${body}`;
}
